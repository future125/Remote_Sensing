int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
HAL_ADCEx_Calibration_Start(&hadc1);  //AD校准
HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);  
__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, 500);  //设置PWM占空比为2.5%
HAL_Delay(1500);
__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2,1500);
HAL_Delay(1500);
__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2,2000);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    s_loopCnt++;  //心跳：Live Watch里不�?? = 程序没在�??
    uint32_t sum=0;
    for(int j=0;j<8;j++)
    {
      if(HAL_ADC_Start(&hadc1) == HAL_OK&&HAL_ADC_PollForConversion(&hadc1, 10) == HAL_OK)  //启动ADC
      {
       sum+=HAL_ADC_GetValue(&hadc1);  //获取ADC值
      }
      HAL_Delay(2);  //延时2ms，等待ADC稳定
    }

    uint16_t adc_filtered=sum/8;  //取平均值
    Voltage_Value[0]=adc_filtered*3.3f/4095.0f;  //计算电压值，单位V
    if(adc_filtered>adc_center+30||adc_filtered<adc_center-30)  //如果偏离中值超过30，则认为有偏差
    {
      uint32_t pulse=500+(uint32_t)adc_filtered*2000/4095;  //计算PWM占空比，范围500~2500
       if(pulse<500)pulse=500;//下限
    if(pulse>2500)pulse=2500;//上限
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2,pulse);//设置
    }
    
    HAL_Delay(15);
  }
  /* USER CODE END 3 */
}

